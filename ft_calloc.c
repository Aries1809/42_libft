#include "libft.h"

void	*ft_calloc(size_t count, size_t size)
{
	void	*p;
	size_t	total;

	total = count * size;
	if (count != 0 && (total / count) != size)
		return (NULL);
	p = malloc(total);
	if (p == NULL)
		return (NULL);
	ft_memset(p, 0, total);
	return (p);
}
